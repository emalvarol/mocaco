from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import polars as pl


@dataclass(frozen=True)
class ConvergenceResult:
    """
    Common result returned by convergence criteria.

    Parameters
    ----------
    method
        Name of the convergence criterion.
    data
        Full diagnostic DataFrame generated by the criterion.
    converged
        Whether the final evaluated state satisfies the criterion.
    estimate
        Final estimate of the target quantity.
    error
        Final estimated error.
    n
        Number of samples used in the final estimate.
    diagnostics
        Method-specific diagnostic information.
    """

    method: str
    data: pl.DataFrame
    converged: bool
    estimate: float | None
    error: float | None
    n: int
    diagnostics: dict[str, Any] = field(default_factory=dict)

    @property
    def is_converged(self) -> bool:
        """Alias for ``converged``."""
        return self.converged

    def to_polars(self) -> pl.DataFrame:
        """Return the complete diagnostic DataFrame."""
        return self.data

    def __str__(self) -> str:
        return str(self.data)

    def __repr__(self) -> str:
        return (
            f"ConvergenceResult("
            f"method={self.method!r}, "
            f"converged={self.converged!r}, "
            f"estimate={self.estimate!r}, "
            f"error={self.error!r}, "
            f"n={self.n!r}"
            f")"
        )
